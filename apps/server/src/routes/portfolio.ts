import { randomBytes } from "node:crypto";
import type { FastifyInstance } from "fastify";
import type { Pool } from "pg";
import { z } from "zod/v4";
import { isPortfolioAuthorization, portfolioGrant } from "../portfolio/auth.js";
import {
  ExportTooLarge,
  PortfolioStore,
  type Evidence,
} from "../portfolio/store.js";

declare module "fastify" {
  interface FastifyContextConfig {
    portfolioReader?: boolean;
  }
}

const querySchema = z
  .object({
    from: z.iso.datetime({ offset: true }).optional(),
    to: z.iso.datetime({ offset: true }).optional(),
    limit: z.coerce.number().int().min(1).max(100).default(50),
    cursor: z
      .string()
      .regex(/^[a-f0-9]{48}:[0-9]{1,5}$/)
      .optional(),
  })
  .strict();
const TTL_MS = 15 * 60 * 1000;
const MAX_SNAPSHOTS = 8;
type Snapshot = {
  grant: string;
  expires: number;
  at: string;
  from: string;
  to: string;
  records: Evidence[];
};

/** Install ahead of the general auth hook, including its first-run bypass. */
export function registerPortfolioBoundary(app: FastifyInstance) {
  app.addHook("onRequest", async (request, reply) => {
    if (
      isPortfolioAuthorization(request.headers.authorization) &&
      (!request.routeOptions.config.portfolioReader || request.method !== "GET")
    ) {
      return reply.code(403).send({
        error: "Portfolio credentials only authorize portfolio reads.",
      });
    }
  });
}

export async function registerPortfolioRoutes(
  app: FastifyInstance,
  pool: Pool
) {
  const store = new PortfolioStore(pool);
  const snapshots = new Map<string, Snapshot>();
  let pending = 0;
  app.addHook("onClose", async () => {
    snapshots.clear();
  });
  app.get(
    "/api/v1/portfolio/v1/export",
    {
      config: { portfolioReader: true },
      // HEAD would otherwise be generated by Fastify. It is not an export method.
      exposeHeadRoute: false,
    },
    async (request, reply) => {
      reply.header("Cache-Control", "no-store");
      const grant = await portfolioGrant(pool, request.headers.authorization);
      if (!grant)
        return reply
          .code(401)
          .send({ error: "Portfolio credential required." });
      const parsed = querySchema.safeParse(request.query);
      if (!parsed.success)
        return reply.code(400).send({ error: "Invalid export query." });
      const query = parsed.data;
      const binding = JSON.stringify({
        ...grant,
        projectIds: [...new Set(grant.projectIds)].sort(),
      });
      for (const [id, snapshot] of snapshots)
        if (snapshot.expires <= Date.now()) snapshots.delete(id);
      let id: string;
      let offset = 0;
      let snapshot: Snapshot;
      if (query.cursor) {
        const [key, position] = query.cursor.split(":");
        const found = snapshots.get(key!);
        if (!found || found.grant !== binding)
          return reply.code(410).send({
            error: "Export expired or scope changed; restart collection.",
          });
        id = key!;
        offset = Number(position);
        snapshot = found;
        if (
          offset > snapshot.records.length ||
          (query.from &&
            new Date(query.from).toISOString() !== snapshot.from) ||
          (query.to && new Date(query.to).toISOString() !== snapshot.to)
        ) {
          return reply.code(400).send({ error: "Cursor/window mismatch." });
        }
      } else {
        if (
          !query.from ||
          !query.to ||
          Date.parse(query.from) >= Date.parse(query.to) ||
          Date.parse(query.to) > Date.now()
        ) {
          return reply
            .code(400)
            .send({ error: "Supply a past half-open UTC window: from < to." });
        }
        if (snapshots.size + pending >= MAX_SNAPSHOTS)
          return reply
            .code(429)
            .send({ error: "Export capacity reached; retry after expiry." });
        pending++;
        try {
          const from = new Date(query.from).toISOString();
          const to = new Date(query.to).toISOString();
          const result = await store.snapshot(grant.projectIds, from, to);
          // Recheck after the read: revocation during materialization must not publish a page.
          const current = await portfolioGrant(
            pool,
            request.headers.authorization
          );
          if (
            !current ||
            JSON.stringify({
              ...current,
              projectIds: [...new Set(current.projectIds)].sort(),
            }) !== binding
          ) {
            return reply.code(401).send({ error: "Portfolio scope changed." });
          }
          id = randomBytes(24).toString("hex");
          snapshot = {
            ...result,
            grant: binding,
            from,
            to,
            expires: Date.now() + TTL_MS,
          };
          snapshots.set(id, snapshot);
        } catch (error) {
          if (error instanceof ExportTooLarge)
            return reply.code(413).send({
              error:
                "Export exceeds bounded snapshot capacity; collection unavailable.",
            });
          throw error;
        } finally {
          pending--;
        }
      }
      // Recheck membership even for cached entities. Excluded inventory has no content.
      const records = snapshot.records.slice(offset, offset + query.limit);
      if (
        records.some(
          (record) =>
            record.type !== "project" &&
            !grant.projectIds.includes(record.projectId)
        )
      ) {
        return reply.code(403).send({ error: "Project outside allowlist." });
      }
      const next = offset + records.length;
      return {
        version: "dispatch.portfolio.v1",
        snapshotAt: snapshot.at,
        expiresAt: new Date(snapshot.expires).toISOString(),
        window: {
          from: snapshot.from,
          to: snapshot.to,
          semantics:
            "outcome_updated_at_[from,to); current_inventory_and_board",
        },
        coverage: {
          history: "current_retained_state_only",
          deletions: "unavailable_no_tombstone_log",
          sessions:
            "explicit_project_membership_only; retained_blocks; no_raw_traces",
          omittedContent: [
            "excluded_projects",
            "unassociated_sessions",
            "tool_traces",
            "attachments",
            "block_data_and_state",
          ],
          text: "bounded_reported_prose; credential_patterns_withheld; no_semantic_secret_detection",
          acceptance: "task_body; no_separate_acceptance_field",
        },
        records,
        pageCursor: `${id}:${offset}`,
        nextCursor: next < snapshot.records.length ? `${id}:${next}` : null,
      };
    }
  );
}
