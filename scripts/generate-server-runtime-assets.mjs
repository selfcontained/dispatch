#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const serverSrcDir = path.join(repoRoot, "apps", "server", "src");
const generatedDir = path.join(serverSrcDir, "generated");
const manifestFile = path.join(generatedDir, "runtime-assets.js");

const webDistDir = path.join(repoRoot, "apps", "web", "dist");
const legacyPublicDir = path.join(repoRoot, "public");
const sourceStaticDir = existsSync(webDistDir) ? webDistDir : legacyPublicDir;
const releaseNotesSource = path.join(repoRoot, "release-notes", "current.md");
const migrationsSourceDir = path.join(serverSrcDir, "db", "migrations");

const MIME_TYPES = new Map([
  [".css", "text/css; charset=utf-8"],
  [".gif", "image/gif"],
  [".html", "text/html; charset=utf-8"],
  [".ico", "image/x-icon"],
  [".jpeg", "image/jpeg"],
  [".jpg", "image/jpeg"],
  [".js", "text/javascript; charset=utf-8"],
  [".json", "application/json; charset=utf-8"],
  [".map", "application/json; charset=utf-8"],
  [".md", "text/markdown; charset=utf-8"],
  [".mp4", "video/mp4"],
  [".png", "image/png"],
  [".svg", "image/svg+xml"],
  [".txt", "text/plain; charset=utf-8"],
  [".webmanifest", "application/manifest+json; charset=utf-8"],
  [".webp", "image/webp"],
  [".woff", "font/woff"],
  [".woff2", "font/woff2"],
]);

function toPosix(filePath) {
  return filePath.split(path.sep).join("/");
}

function listFiles(dir) {
  const entries = readdirSync(dir, { withFileTypes: true });
  return entries.flatMap((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return listFiles(fullPath);
    }
    return [fullPath];
  });
}

function mimeTypeFor(filePath) {
  return (
    MIME_TYPES.get(path.extname(filePath).toLowerCase()) ??
    "application/octet-stream"
  );
}

const staticFiles = listFiles(sourceStaticDir)
  .map((absolutePath) => {
    const relativePath = toPosix(path.relative(sourceStaticDir, absolutePath));
    return {
      routePath: `/${relativePath}`,
      contentType: mimeTypeFor(absolutePath),
      base64: readFileSync(absolutePath).toString("base64"),
    };
  })
  .sort((a, b) => a.routePath.localeCompare(b.routePath));

const migrationFiles = listFiles(migrationsSourceDir)
  .map((absolutePath) => {
    const relativePath = toPosix(
      path.relative(migrationsSourceDir, absolutePath)
    );
    return {
      name: path.basename(relativePath),
      sql: readFileSync(absolutePath, "utf8"),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const releaseNotesMarkdown = existsSync(releaseNotesSource)
  ? readFileSync(releaseNotesSource, "utf8")
  : "";

const lines = [];
lines.push("// Generated by scripts/generate-server-runtime-assets.mjs");
lines.push("// Do not edit by hand.");
lines.push("");
lines.push("export const staticFiles = [");
staticFiles.forEach((asset) => {
  lines.push(
    `  { routePath: ${JSON.stringify(asset.routePath)}, contentType: ${JSON.stringify(asset.contentType)}, base64: ${JSON.stringify(asset.base64)} },`
  );
});
lines.push("];");
lines.push("");
lines.push("export const migrationFiles = [");
migrationFiles.forEach((asset) => {
  lines.push(
    `  { name: ${JSON.stringify(asset.name)}, sql: ${JSON.stringify(asset.sql)} },`
  );
});
lines.push("];");
lines.push("");
lines.push(
  `export const releaseNotesMarkdown = ${JSON.stringify(releaseNotesMarkdown)};`
);
lines.push("");

mkdirSync(generatedDir, { recursive: true });
writeFileSync(manifestFile, `${lines.join("\n")}\n`, "utf8");

console.log(
  `Generated Dispatch runtime assets from ${path.relative(repoRoot, sourceStaticDir)} (${staticFiles.length} static files, ${migrationFiles.length} migrations)`
);
